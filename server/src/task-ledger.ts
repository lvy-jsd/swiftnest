/**
 * Task ledger: a thin, read-only mirror of the team's live work.
 *
 * It polls the DS Bot `state` endpoint (POST /api/bot) for `live.work` — who is running,
 * what they run, who they wait for, and how long — and appends each change as an event.
 * The events are the ledger: an append is idempotent on its `liveKey`, so a change seen
 * twice lands once. Two read-only endpoints expose the ledger; stopping and steering reuse
 * the existing endpoints, so this file never writes to the team.
 */
import type { IncomingMessage, ServerResponse } from 'node:http';
import { text } from '@swiftnest/core';
import { readJsonFile, JsonFileWriter } from './json-store.js';
import { HttpError } from './http.js';
import type { DeviceHub } from './device-routes.js';

/** The `live.work` block of a DS Bot `state` answer: who runs, what, and who they wait for. */
export interface LiveWork {
  bots: Record<string, unknown>;
  rooms: Record<string, unknown>;
  approvals: unknown[];
  waiting: Record<string, unknown>;
  turns: Record<string, unknown>;
  steered: Record<string, unknown>;
}

/** One ledger entry: a change in the team's live work, recorded once per `liveKey`. */
export interface TaskEvent {
  /** Monotonic, generated by the ledger; the order events were recorded. */
  seq: number;
  /** When the change was recorded, epoch milliseconds. */
  at: number;
  /** The `state` answer's `liveKey`; the dedup key, generated by DS Bot. */
  liveKey: string;
  /** The `live.work` snapshot that triggered the change. */
  work: LiveWork;
}

/** One unit of work as the endpoints expose it. */
export interface TaskView {
  id: string;
  /** One of `running`, `waiting`, `queued`, `completed`, `failed`; the ledger emits the first three today. */
  status: string;
  /** Epoch milliseconds of the latest event for this unit. */
  updatedAt: number;
  events: TaskEvent[];
}

const emptyWork = (): LiveWork => ({ bots: {}, rooms: {}, approvals: [], waiting: {}, turns: {}, steered: {} });

/**
 * A work unit's status from the latest snapshot: `running` while it runs a turn, `waiting`
 * while it waits for a hand-back, `completed` once it leaves the live view. `queued` and
 * `failed` are in the contract but live.work carries no signal for them yet, so the ledger
 * does not emit them.
 */
function statusOf(id: string, latest: TaskEvent): string {
  if (id in latest.work.bots || id in latest.work.rooms) return 'running';
  if (id in latest.work.waiting) return 'waiting';
  return 'completed';
}

/** Whether a work unit is live in a snapshot: running a turn, in a room, or waiting for a hand-back. */
function presentIn(id: string, work: LiveWork): boolean {
  return id in work.bots || id in work.rooms || id in work.waiting;
}

/**
 * The append-only ledger. `append` is idempotent on `liveKey`; `list` and `get` read the
 * latest snapshot; `start` polls DS Bot and feeds changes in. Nothing here writes to the team.
 */
export class TaskLedger {
  private events: TaskEvent[] = [];
  private seen = new Set<string>();
  private seq = 0;
  private writer: JsonFileWriter;
  private lastKey?: string;
  private timer?: NodeJS.Timeout;

  constructor(file: string) {
    this.writer = new JsonFileWriter(file);
    const saved = readJsonFile(file) as { seq?: number; events?: TaskEvent[] } | undefined;
    if (saved?.events) {
      this.events = saved.events;
      this.seq = saved.seq ?? saved.events.length;
      for (const event of this.events) this.seen.add(event.liveKey);
    }
  }

  /** Record a live-work change; a `liveKey` already recorded lands once. Returns the event, or undefined on a duplicate. */
  append(liveKey: string, work: LiveWork): TaskEvent | undefined {
    if (this.seen.has(liveKey)) return undefined;
    this.seen.add(liveKey);
    const event: TaskEvent = { seq: ++this.seq, at: Date.now(), liveKey, work };
    this.events.push(event);
    void this.writer.write({ seq: this.seq, events: this.events }, () => {});
    return event;
  }

  /** Every work unit ever seen, newest first; a finished unit stays listed as `completed`. */
  list(): TaskView[] {
    if (!this.events.length) return [];
    const ids = new Set<string>();
    for (const event of this.events) {
      for (const id of Object.keys(event.work.bots)) ids.add(id);
      for (const id of Object.keys(event.work.rooms)) ids.add(id);
    }
    return [...ids].map((id) => this.get(id)!);
  }

  /** One work unit's history, or undefined when it was never seen. The leaving event counts as its. */
  get(id: string): TaskView | undefined {
    const events: TaskEvent[] = [];
    for (let i = 0; i < this.events.length; i++) {
      const e = this.events[i]!;
      const prev = i > 0 ? this.events[i - 1]! : undefined;
      const present = presentIn(id, e.work);
      if (present || (prev !== undefined && presentIn(id, prev.work) && !present)) events.push(e);
    }
    const latest = events.at(-1);
    if (!latest) return undefined;
    return { id, status: statusOf(id, this.events.at(-1)!), updatedAt: latest.at, events };
  }

  /** Begin polling DS Bot for live-work changes; `source` is re-read each poll so a kernel restart is picked up. */
  start(source: () => { url: string; token: string }): void {
    if (this.timer) return;
    const poll = async () => {
      try {
        const { url, token } = source();
        const cookie = await sessionCookie(url, token);
        const res = await fetch(`${url}/api/bot`, {
          method: 'POST',
          headers: { 'content-type': 'application/json', cookie },
          body: JSON.stringify({ endpoint: 'state', payload: { live: this.lastKey } }),
        });
        if (!res.ok) throw new Error(`state ${res.status}`);
        const body = (await res.json()) as { ok?: boolean; value?: { liveKey?: string; work?: LiveWork } };
        const value = body.value;
        if (body.ok && value?.liveKey && value.liveKey !== this.lastKey) {
          this.lastKey = value.liveKey;
          this.append(value.liveKey, value.work ?? emptyWork());
        }
      } catch {
        // DSH is restarting or the token changed; the next poll retries.
      } finally {
        this.timer = setTimeout(poll, 2000);
        this.timer.unref();
      }
    };
    void poll();
  }

  stop(): void {
    if (this.timer) clearTimeout(this.timer);
    this.timer = undefined;
  }

  async flush(): Promise<void> {
    await this.writer.flush();
  }
}

/** Trade the kernel's launch token for a session cookie, at `/connect` (falling back to `/`). */
async function sessionCookie(url: string, token: string): Promise<string> {
  for (const path of ['/connect', '/']) {
    const res = await fetch(`${url}${path}?token=${encodeURIComponent(token)}`, { redirect: 'manual' });
    const setCookie = res.headers.get('set-cookie');
    if (setCookie) return setCookie.split(';')[0]!;
  }
  return '';
}

/** The two read-only endpoints: `GET /swiftnest/api/tasks` and `GET /swiftnest/api/tasks/{id}`. */
export async function handleTaskRoute(
  hub: DeviceHub,
  req: IncomingMessage,
  _res: ServerResponse,
  url: URL,
): Promise<unknown> {
  const path = url.pathname;
  if (path === '/swiftnest/api/tasks' && req.method === 'GET') return hub.ledger.list();
  const match = /^\/swiftnest\/api\/tasks\/([^/]+)$/.exec(path);
  if (match && req.method === 'GET') {
    const task = hub.ledger.get(decodeURIComponent(match[1]!));
    if (!task) throw new HttpError(404, text('notFound'));
    return task;
  }
  throw new HttpError(404, text('notFound'));
}
